"""An agent-facing environment for worst-case activity search (LLM-as-policy baseline).

  python scripts/llm_env.py task  --block mac --top mac_p2 --dir TASKDIR [--budget 256] [--finite-only]
  python scripts/llm_env.py score --dir TASKDIR candidates.json
  python scripts/llm_env.py finish --dir TASKDIR --config mac_p2_gate --seed 0

`task` writes a self-contained task folder: the block's XLS-generated RTL, a spec
(task.md) and a budget ledger. It contains no results, so an agent given only this
folder is not contaminated by what other methods found.

`score` is the only feedback channel. Candidates go through the same fail-closed
scorer (gates + gate-level proxy) as every other search method; every candidate
costs one evaluation, the ledger refuses anything past the budget, and rejected
attempts that beat the legal best go to the reward-hacking log.

`finish` writes the agent's results as a search run (method "llm") so that
scripts/validate_search.py validates them post-route like any other method.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

import numpy as np

from xpr.blocks import BLOCKS
from xpr.gates import RejectLog
from xpr.proxy import Proxy
from xpr.search import objectives
from xpr.search.space import Scorer, Space

PERIOD = 8

OBJECTIVE_TEXT = {
    "alpha": """Maximize the mean toggle rate of the synthesized gate-level netlist's nets (alpha, in toggles per
net bit per cycle) over the window. Higher alpha means higher dynamic power.""",
    "swing": """Maximize the cycle-to-cycle power swing at a period of {period} cycles: the amplitude of the
{period}-cycle component of the per-cycle toggle-rate waveform of the synthesized gate-level netlist
(toggles per net bit per cycle). Think of the supply current oscillating at 1/{period} of the clock
frequency, as a di/dt stressmark that excites a power-delivery resonance. Average activity alone does
not score: a pattern whose activity is the same every cycle has zero swing.""",
}

LAYOUTS = {
    "mac": """data[16:0] = { a[7:0], b[7:0], last }  (a and b are signed 8-bit, two's complement)
Each accepted input adds a*b to a 32-bit accumulator; an input with last=1 outputs the sum and clears it.""",
    "bf16_mul": """data[31:0] = { a[15:0], b[15:0] }  (a and b are bfloat16: sign[15], exponent[14:7], fraction[6:0])
Each accepted input outputs the bf16 product a*b.""",
    "matmul4": """data[34:0] = { load[34], row[33:32], x[31:0] },  x = four signed 8-bit lanes, lane i in bits [8*i+7 : 8*i]
load=1: weight row `row` <- x (stored; no output).  load=0: x is an activation vector; outputs y = x . W
(y[c] = sum_r x[r] * W[r][c], four s32 results).  Weights reset to zero.""",
}
LAYOUTS["systolic4"] = LAYOUTS["systolic4_iso"] = LAYOUTS["matmul4"]  # same interface


def task(args) -> None:
    block = BLOCKS[args.block]
    run_dir = Path.home() / "runs" / "orfs" / args.top
    d = Path(args.dir)
    d.mkdir(parents=True, exist_ok=True)
    shutil.copy(run_dir / f"{args.top}.v", d / "rtl.v")
    width = block.IN_W + 2
    finite = ("\n- Finite operands only: no bf16 operand may have an all-ones exponent (Inf/NaN)."
              if args.finite_only else "")
    (d / "task.md").write_text(f"""# Task: find the input stream that maximizes switching activity

The design is `rtl.v` (module `{args.top}`), a pipelined streaming block generated by Google XLS
and implemented in the ASAP7 7 nm library. Read it to understand the datapath.

## Interface
Each clock cycle the testbench drives one {width}-bit input word, most significant bit first:
`{{ rst, valid, data[{block.IN_W - 1}:0] }}`. The output side is always ready.

{LAYOUTS[block.NAME]}

## What you control
A candidate is a pattern of exactly {PERIOD} input words. After a 4-cycle reset, the pattern is
repeated continuously; activity is measured over a 256-cycle window that starts after the pipeline
has filled.

## Objective
{OBJECTIVE_TEXT[args.objective].format(period=args.swing_period)}

## Rules (fail-closed: a violating candidate scores 0)
- rst must be 0 in every word of the pattern (reset only happens before the pattern).
- valid must be 1 in at least one word of the pattern.
- The handshake must not stall (it won't, as long as the rules above hold).{finite}

## Budget and scoring
You have {args.budget} evaluations in total. Each candidate you submit costs one, including
duplicates and rule violations. Score candidates by writing a JSON file:

    [ [w0, w1, w2, w3, w4, w5, w6, w7], ... ]      # one list of {PERIOD} words per candidate

Each word is either an integer (the full {width}-bit word, e.g. "0x1abcd" as a string or a number), or
an object {{"rst": 0, "valid": 1, "data": <int>}}. Then run the scoring command you were given.
It prints each candidate's score (or the rules it broke) and the budget left.
""")
    (d / "ledger.json").write_text(json.dumps({
        "block": block.NAME, "top": args.top, "budget": args.budget, "used": 0, "best": 0.0,
        "finite_only": args.finite_only, "proxy_level": "synth", "period": PERIOD,
        "objective": args.objective, "swing_period": args.swing_period}, indent=2))
    (d / "work").mkdir(exist_ok=True)  # the agent's own scratch space for helper scripts
    (d / "history.jsonl").write_text("")
    print(f"task written to {d}")


def _parse(cands, width: int) -> np.ndarray:
    out = []
    for cand in cands:
        if len(cand) != PERIOD:
            raise ValueError(f"each candidate needs exactly {PERIOD} words, got {len(cand)}")
        rows = []
        for w in cand:
            if isinstance(w, dict):
                word = (int(w["rst"]) << (width - 1)) | (int(w["valid"]) << (width - 2)) | int(w["data"])
            else:
                word = int(w, 0) if isinstance(w, str) else int(w)
            if word < 0 or word >> width:
                raise ValueError(f"word {word:#x} does not fit in {width} bits")
            rows.append([(word >> (width - 1 - i)) & 1 for i in range(width)])
        out.append(rows)
    return np.array(out, bool)


def score(args) -> None:
    d = Path(args.dir)
    led = json.loads((d / "ledger.json").read_text())
    block = BLOCKS[led["block"]]
    space = Space(block, period=PERIOD, finite_only=led["finite_only"])
    remaining = led["budget"] - led["used"]
    if remaining <= 0:
        sys.exit("budget exhausted: no evaluations left")
    try:
        pats = _parse(json.loads(Path(args.candidates).read_text()), space.width)
    except (ValueError, KeyError, TypeError, json.JSONDecodeError) as e:
        sys.exit(f"invalid candidate file (no evaluations charged): {e}")
    if len(pats) > remaining:
        print(f"only {remaining} evaluations left: scoring the first {remaining} of {len(pats)}")
        pats = pats[:remaining]
    run_dir = Path.home() / "runs" / "orfs" / led["top"]
    swing = led.get("objective", "alpha") == "swing"
    objective = objectives.swing(led["swing_period"]) if swing else None
    with Proxy.build(block, run_dir, led["top"], level="synth", per_cycle=swing) as proxy:
        sc = Scorer(space, proxy, len(pats), RejectLog(d / "rejects.jsonl"),
                    {"method": "llm", "dir": str(d)}, objective)
        sc.best = led["best"]
        scores = sc.score(pats, tag="llm")
    with open(d / "history.jsonl", "a") as f:
        for i, (p, s) in enumerate(zip(pats, scores)):
            verdict = space.gates(p, sc.result(p))
            f.write(json.dumps({"eval": led["used"] + i + 1, "score": float(s),
                                "failed": verdict.failed, "pattern": p.astype(int).tolist()}) + "\n")
            label = "swing" if swing else "alpha"
            print(f"candidate {i}: " + (f"{label}={s:.4f}" if s > 0 else f"REJECTED {verdict.failed}"))
    led["used"] += len(pats)
    led["best"] = max(led["best"], float(scores.max(initial=0.0)))
    (d / "ledger.json").write_text(json.dumps(led, indent=2))
    print(f"best so far {led['best']:.4f}; evaluations used {led['used']}/{led['budget']}")


def finish(args) -> None:
    """Write the agent's run in search.py's result format for validate_search.py."""
    d = Path(args.dir)
    led = json.loads((d / "ledger.json").read_text())
    hist = [json.loads(l) for l in (d / "history.jsonl").read_text().splitlines() if l.strip()]
    legal = sorted((h for h in hist if h["score"] > 0), key=lambda h: -h["score"])
    seen, top = set(), []
    for h in legal:
        key = json.dumps(h["pattern"])
        if key not in seen:
            seen.add(key)
            top.append({"alpha": h["score"], "pattern": h["pattern"]})
    best, curve = 0.0, []
    for h in hist:
        best = max(best, h["score"])
        curve.append((h["eval"], best))
    out = Path.home() / "runs" / "search" / args.config
    out.mkdir(parents=True, exist_ok=True)
    rejects = {}
    for h in hist:
        for name in h["failed"]:
            rejects[name] = rejects.get(name, 0) + 1
    result = {"block": led["block"], "top": led["top"], "method": "llm", "seed": args.seed,
              "period": PERIOD, "finite_only": led["finite_only"], "proxy_level": "synth",
              "objective": led.get("objective", "alpha"), "swing_period": led.get("swing_period", 8),
              "budget": led["budget"], "best": best, "curve": curve,
              "rejects": rejects, "top": top[:10], "task_dir": str(d)}
    (out / f"llm_s{args.seed}.json").write_text(json.dumps(result))
    print(f"wrote {out / f'llm_s{args.seed}.json'}: best {best:.4f} in {led['used']} evaluations")


def main() -> None:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    t = sub.add_parser("task")
    t.add_argument("--block", required=True, choices=BLOCKS)
    t.add_argument("--top", required=True)
    t.add_argument("--dir", required=True)
    t.add_argument("--budget", type=int, default=256)
    t.add_argument("--finite-only", action="store_true")
    t.add_argument("--objective", default="alpha", choices=["alpha", "swing"])
    t.add_argument("--swing-period", type=int, default=8)
    s = sub.add_parser("score")
    s.add_argument("--dir", required=True)
    s.add_argument("candidates")
    f = sub.add_parser("finish")
    f.add_argument("--dir", required=True)
    f.add_argument("--config", required=True)
    f.add_argument("--seed", type=int, default=0)
    args = ap.parse_args()
    {"task": task, "score": score, "finish": finish}[args.cmd](args)


if __name__ == "__main__":
    main()
