"""Generate an N x N INT8 weight-stationary systolic array as an explicit XLS proc network.

  python designs/systolic/gen_systolic.py N [--isolate] > designs/systolic/systolic<N>[_iso].x

Why generated: in this XLS release's DSLX interpreter, sends issued from inside
`unroll_for!` in a spawned proc's `next()` are silently not delivered (see
docs/decisions.md for the minimal repro). Writing every send, recv and spawn out
explicitly avoids the construct and gives plain, readable DSLX.

Structure follows XLS's xls/examples/matmul_4x4/matmul_4x4.x (Apache-2.0): one Node
proc per PE, activations flowing east, partial sums flowing south. Original changes:
INT8 operands with s32 sums, weights reloadable through the input stream, a
Distributor/Collector pair so the array pipelines fully, and optional operand
isolation (the multiplier holds its previous operand on weight-load words).

Interface (identical to designs/matmul4 at N = 4, and to xpr.blocks.matmul4's model):
  input  { load: bool, row: uN[RB], x: s8[N] }   load=1: W[row] <- x; load=0: compute
  output s32[N] for load=0 words: y[c] = sum_r x[r] * W[r][c] (weights before this word)
"""

from __future__ import annotations

import argparse
import math


def generate(n: int, isolate: bool) -> str:
    rb = max(1, math.ceil(math.log2(n)))
    top = f"Systolic{n}" + ("Iso" if isolate else "")
    iso = "true" if isolate else "false"
    L = []
    w = L.append
    w(f"// GENERATED by designs/systolic/gen_systolic.py {n}{' --isolate' if isolate else ''}. Do not edit.")
    w(f"// INT8 {n}x{n} weight-stationary systolic array, XLS proc network; operand isolation: {iso}.")
    w("")
    w("// Depth of every internal channel's FIFO. Codegen needs an explicit depth; 2 keeps the")
    w("// array at full throughput (a depth-1 FIFO cannot accept while it is being drained).")
    w("const FIFO_DEPTH = u32:2;")
    w("")
    w(f"pub struct ArrIn {{ load: bool, row: u{rb}, x: s8[{n}] }}")
    w("pub struct NodeCtl { load: bool, w: s8 }")
    w("")
    # Two node variants: NodeE forwards the activation east; NodeLast (last column) does not.
    # Draining activations off the east edge into the collector creates a circular wait with
    # bounded FIFOs (a last-column node blocks on its east send while the collector waits on
    # a south value), and the drained values are discarded anyway.
    for name, has_east in (("NodeE", True), ("NodeLast", False)):
        w(f"proc {name} {{")
        w("    ctl: chan<NodeCtl> in;")
        w("    west: chan<s8> in;")
        w("    north: chan<s32> in;")
        if has_east:
            w("    east: chan<s8> out;")
        w("    south: chan<s32> out;")
        args = "ctl: chan<NodeCtl> in, west: chan<s8> in, north: chan<s32> in, "
        args += ("east: chan<s8> out, " if has_east else "") + "south: chan<s32> out"
        members = "ctl, west, north, " + ("east, " if has_east else "") + "south"
        w(f"    config({args}) {{ ({members}) }}")
        w("    // State: (weight, last activation fed to the multiplier).")
        w("    init { (s8:0, s8:0) }")
        w("    next(state: (s8, s8)) {")
        w("        let (w, last_a) = state;")
        w("        let (t0, c) = recv(join(), ctl);")
        w("        let (t1, a) = recv(join(), west);")
        w("        let (t2, ps) = recv(join(), north);")
        w("        let tok = join(t0, t1, t2);")
        if isolate:
            w("        // Operand isolation: hold the multiplier's operand on weight-load words.")
            w("        let a_mul = if c.load { last_a } else { a };")
        else:
            w("        let a_mul = a;")
        w("        let sum = ps + (a_mul as s32) * (w as s32);")
        # Sends are top-level statements, chained by token. In this XLS release's DSLX
        # interpreter, sends nested inside an unused `join(...)` expression are dropped.
        if has_east:
            w("        let te = send(tok, east, a);")
            w("        send(te, south, sum);")
        else:
            w("        send(tok, south, sum);")
        w("        (if c.load { c.w } else { w }, a_mul)")
        w("    }")
        w("}")
        w("")
    # Distributor: one word in; per-node control, west activations, north zeros, emit flag out.
    w("proc Distributor {")
    w("    in_r: chan<ArrIn> in;")
    w(f"    ctls: chan<NodeCtl>[{n * n}] out;")
    w(f"    wests: chan<s8>[{n}] out;")
    w(f"    norths: chan<s32>[{n}] out;")
    w("    emit: chan<bool> out;")
    w(f"    config(in_r: chan<ArrIn> in, ctls: chan<NodeCtl>[{n * n}] out, wests: chan<s8>[{n}] out,")
    w(f"           norths: chan<s32>[{n}] out, emit: chan<bool> out) {{ (in_r, ctls, wests, norths, emit) }}")
    w("    init { () }")
    w("    next(state: ()) {")
    w("        let (tok, m) = recv(join(), in_r);")
    toks = []
    for r in range(n):
        for c in range(n):
            w(f"        let k{r}_{c} = send(tok, ctls[{r * n + c}], "
              f"NodeCtl {{ load: m.load && m.row == u{rb}:{r}, w: m.x[{c}] }});")
            toks.append(f"k{r}_{c}")
    for r in range(n):
        w(f"        let a{r} = send(tok, wests[{r}], m.x[{r}]);")
        toks.append(f"a{r}")
    for c in range(n):
        w(f"        let z{c} = send(tok, norths[{c}], s32:0);")
        toks.append(f"z{c}")
    w(f"        let tok = join({', '.join(toks)});")
    w("        send(tok, emit, !m.load);")
    w("    }")
    w("}")
    w("")
    # Collector: south edge -> y, emitted on compute words.
    w("proc Collector {")
    w(f"    souths: chan<s32>[{n}] in;")
    w("    emit: chan<bool> in;")
    w(f"    out_s: chan<s32[{n}]> out;")
    w(f"    config(souths: chan<s32>[{n}] in, emit: chan<bool> in, out_s: chan<s32[{n}]> out) {{")
    w("        (souths, emit, out_s)")
    w("    }")
    w("    init { () }")
    w("    next(state: ()) {")
    w("        let (t, e) = recv(join(), emit);")
    toks = ["t"]
    for c in range(n):
        # (Names like s0/s1 are reserved: sN is a DSLX type.)
        w(f"        let (ts{c}, y{c}) = recv(join(), souths[{c}]);")
        toks.append(f"ts{c}")
    w(f"        let tok = join({', '.join(toks)});")
    w(f"        send_if(tok, out_s, e, s32[{n}]:[{', '.join(f'y{c}' for c in range(n))}]);")
    w("    }")
    w("}")
    w("")
    # Top: flat channel arrays. ew[(c-1)*n + r]: activation entering column c >= 1 of row r.
    # ns[(r-1)*n + c]: partial sum entering row r >= 1 of column c. Edges have their own arrays.
    w(f"pub proc {top} {{")
    w(f"    config(in_r: chan<ArrIn> in, out_s: chan<s32[{n}]> out) {{")
    w(f"        let (ctl_s, ctl_r) = chan<NodeCtl, FIFO_DEPTH>[{n * n}](\"ctl\");")
    w(f"        let (west_s, west_r) = chan<s8, FIFO_DEPTH>[{n}](\"west_edge\");")
    w(f"        let (north_s, north_r) = chan<s32, FIFO_DEPTH>[{n}](\"north_edge\");")
    if n > 1:
        w(f"        let (ew_s, ew_r) = chan<s8, FIFO_DEPTH>[{(n - 1) * n}](\"east_west\");")
        w(f"        let (ns_s, ns_r) = chan<s32, FIFO_DEPTH>[{(n - 1) * n}](\"north_south\");")
    w(f"        let (south_s, south_r) = chan<s32, FIFO_DEPTH>[{n}](\"south_edge\");")
    w("        let (emit_s, emit_r) = chan<bool, FIFO_DEPTH>(\"emit\");")
    w("        spawn Distributor(in_r, ctl_s, west_s, north_s, emit_s);")
    for r in range(n):
        for c in range(n):
            west = f"west_r[{r}]" if c == 0 else f"ew_r[{(c - 1) * n + r}]"
            north = f"north_r[{c}]" if r == 0 else f"ns_r[{(r - 1) * n + c}]"
            south = f"south_s[{c}]" if r == n - 1 else f"ns_s[{r * n + c}]"
            if c == n - 1:
                w(f"        spawn NodeLast(ctl_r[{r * n + c}], {west}, {north}, {south});")
            else:
                w(f"        spawn NodeE(ctl_r[{r * n + c}], {west}, {north}, ew_s[{c * n + r}], {south});")
    w("        spawn Collector(south_r, emit_r, out_s);")
    w("        ()")
    w("    }")
    w("    init { () }")
    w("    next(state: ()) { () }")
    w("}")
    w("")
    # Self-check against a direct matrix-vector model, on a small stimulus.
    w("#[test_proc]")
    w(f"proc {top}Test {{")
    w("    terminator: chan<bool> out;")
    w("    in_s: chan<ArrIn> out;")
    w(f"    out_r: chan<s32[{n}]> in;")
    w("    config(terminator: chan<bool> out) {")
    w("        let (in_s, in_r) = chan<ArrIn>(\"in\");")
    w(f"        let (out_s, out_r) = chan<s32[{n}]>(\"out\");")
    w(f"        spawn {top}(in_r, out_s);")
    w("        (terminator, in_s, out_r)")
    w("    }")
    w("    init { () }")
    w("    next(state: ()) {")
    W = [[(r * n + c + 1) * (1 if (r + c) % 2 == 0 else -1) for c in range(n)] for r in range(n)]
    xs = [[(i + 1) * (1 if i % 2 == 0 else -1) for i in range(n)], [-128] + [127] * (n - 1)]
    tok = "join()"
    for r in range(n):
        w(f"        let tok = send({tok}, in_s, ArrIn {{ load: true, row: u{rb}:{r}, "
          f"x: s8[{n}]:[{', '.join(map(str, W[r]))}] }});")
        tok = "tok"
    for x in xs:
        w(f"        let tok = send(tok, in_s, ArrIn {{ load: false, row: u{rb}:0, x: s8[{n}]:[{', '.join(map(str, x))}] }});")
    for x in xs:
        y = [sum(x[r] * W[r][c] for r in range(n)) for c in range(n)]
        w("        let (tok, y) = recv(tok, out_r);")
        w(f"        assert_eq(y, s32[{n}]:[{', '.join(map(str, y))}]);")
    w("        send(tok, terminator, true);")
    w("    }")
    w("}")
    return "\n".join(L) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("n", type=int)
    ap.add_argument("--isolate", action="store_true")
    args = ap.parse_args()
    if args.n < 1 or args.n > 8:
        raise SystemExit("n must be in 1..8")
    print(generate(args.n, args.isolate), end="")


if __name__ == "__main__":
    main()
